func rsaEncryptSessionKey(sessionKey []byte) ([]byte, error) {
	key, err := x509.ParsePKIXPublicKey(steamPublicKey)
	if err != nil {
		return nil, err
	}
	return rsa.EncryptOAEP(sha1.New(), rand.Reader, key.(*rsa.PublicKey), sessionKey, nil)
}

func symmetricEncrypt(ciph cipher.Block, src []byte) ([]byte, error) {
	iv := make([]byte, aes.BlockSize)
	if _, err := rand.Read(iv); err != nil {
		return nil, err
	}
	bs := ciph.BlockSize()
	eiv := make([]byte, aes.BlockSize)
	for i := 0; i < len(iv); i += bs {
		ciph.Encrypt(eiv[i:i+bs], iv[i:i+bs])
	}
	pad := aes.BlockSize - len(src)%aes.BlockSize
	padded := make([]byte, len(src)+pad)
	copy(padded, src)
	for i := len(src); i < len(padded); i++ {
		padded[i] = byte(pad)
	}
	out := make([]byte, aes.BlockSize+len(padded))
	copy(out, eiv)
	cipher.NewCBCEncrypter(ciph, iv).CryptBlocks(out[aes.BlockSize:], padded)
	return out, nil
}

func symmetricDecrypt(ciph cipher.Block, src []byte) []byte {
	iv := make([]byte, aes.BlockSize)
	copy(iv, src[:aes.BlockSize])
	bs := ciph.BlockSize()
	for i := 0; i < len(iv); i += bs {
		ciph.Decrypt(iv[i:i+bs], iv[i:i+bs])
	}
	data := make([]byte, len(src)-aes.BlockSize)
	copy(data, src[aes.BlockSize:])
	cipher.NewCBCDecrypter(ciph, iv).CryptBlocks(data, data)
	if n := len(data); n > 0 {
		if pad := int(data[n-1]); pad > 0 && pad <= aes.BlockSize {
			data = data[:n-pad]
		}
	}
	return data
}
